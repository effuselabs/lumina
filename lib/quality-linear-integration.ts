/**

 * Map issue severity to Linear priority
 */
function getPriorityFromSeverity(severity: 'low' | 'medium' | 'high'): number {
    switch (severity) {
        case 'high': return 2; // High priority
        case 'medium': return 3; // Normal priority  
        case 'low': return 4; // Low priority
        default: return 3;
    }
}